let current = 'en';
const listeners = new Set();

function readStored() {
  try { return localStorage.getItem(LANG_KEY); } catch { return null; }
}

export function getLang() { return current; }
export function getLocale() { return LOCALES[current] || 'en-US'; }
export function isSupported(code) { return LANGS.some((l) => l.code === code); }

// Translate `text` (the English source). Unknown strings fall back to English.
export function t(text, params) {
  const dict = CATALOGS[current];
  let msg = dict && Object.prototype.hasOwnProperty.call(dict, text) ? dict[text] : text;
  if (params) {
    msg = msg.replace(/\{(\w+)\}/g, (m, key) => (
      params[key] === undefined || params[key] === null ? m : String(params[key])
    ));
  }
  return msg;
}

export function setLang(code) {
  const next = isSupported(code) ? code : 'en';
  try { localStorage.setItem(LANG_KEY, next); } catch { /* storage unavailable */ }
  if (next === current) return current;
  current = next;
  if (typeof document !== 'undefined') document.documentElement.lang = next;
  for (const fn of listeners) {
    try { fn(next); } catch { /* a listener must not break the others */ }
  }
  return current;
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function initLang() {
  current = readStored() === 'tr' ? 'tr' : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  return current;
}

// Translates static markup carrying data-i18n* attributes (see file header).
export function applyStatic(root = document) {
  if (!root || typeof root.querySelectorAll !== 'function') return;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle));
  for (const el of root.querySelectorAll('[data-i18n-tip]')) el.setAttribute('data-tip', t(el.dataset.i18nTip));
}
